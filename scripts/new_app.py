#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = ROOT / "templates"
EXAMPLES = ROOT / "examples"


def sanitize_id(raw: str) -> str:
    raw = raw.strip().lower()
    raw = re.sub(r"[^a-z0-9_]+", "_", raw)
    raw = raw.strip("_")
    if not raw:
        raw = "myapp"
    if raw[0].isdigit():
        raw = f"app_{raw}"
    return raw


def sanitize_name(raw: str) -> str:
    s = raw.strip()
    if not s:
        return "My App"
    s = re.sub(r"[\r\n\t]+", " ", s)
    s = re.sub(r"\s+", " ", s)
    return s


def render_template(path: Path, mapping: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    for k, v in mapping.items():
        text = text.replace(f"{{{{{k}}}}}", v)
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a Starlight app project in this kit")
    parser.add_argument("--name", required=True, help="Display name (e.g. Calcolatrice)")
    parser.add_argument("--id", help="App id (default: sanitized name)")
    parser.add_argument("--force", action="store_true", help="Overwrite if project exists")
    args = parser.parse_args()

    app_name = sanitize_name(args.name)
    app_id = sanitize_id(args.id if args.id else app_name)

    project_dir = EXAMPLES / app_id
    src_dir = project_dir / "src"
    bundle_dir = project_dir / "bundle"

    if project_dir.exists() and not args.force:
        raise SystemExit(f"Project already exists: {project_dir} (use --force)")

    src_dir.mkdir(parents=True, exist_ok=True)
    bundle_dir.mkdir(parents=True, exist_ok=True)

    mapping = {
        "APP_NAME": app_name,
        "APP_ID": app_id,
    }

    (src_dir / "main.c").write_text(
        render_template(TEMPLATES / "main.c.tpl", mapping),
        encoding="utf-8",
    )
    (bundle_dir / "app.ini").write_text(
        render_template(TEMPLATES / "app.ini.tpl", mapping),
        encoding="utf-8",
    )

    (project_dir / "README.md").write_text(
        "# " + app_name + "\n\n"
        "Project generated by starlight-app-kit.\n\n"
        "- Source: src/main.c\n"
        "- Bundle: bundle/app.ini\n",
        encoding="utf-8",
    )

    print(f"Created project: {project_dir}")
    print(f"Next: make APP_ID={app_id} build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
